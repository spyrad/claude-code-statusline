# claude-code-statusline - a four-line status line for Claude Code on Windows.
#   Model, repo and branch, rate-limit window with a consumption ratio, and context usage.
#
# Usage:
#   powershell -NoProfile -ExecutionPolicy Bypass -File install.ps1 [options]
#   & ([scriptblock]::Create((irm https://raw.githubusercontent.com/spyrad/claude-code-statusline/main/install.ps1))) [options]
#
# Options:
#   -ShowCosts             also show a cost line (reads the local transcripts under
#                          ~/.claude/projects to estimate spend - nothing is sent anywhere)
#   -NoTest                do not render a sample status line at the end
#   -Uninstall             remove the status line entry and the script again
#
# Safe to run repeatedly: an existing entry is detected, all other settings stay
# untouched, and settings.json is backed up before it is changed.
# Generated by build.ps1 - edit src/install-template.ps1, not install.ps1.
param(
    [string]$ClaudeDir = (Join-Path $env:USERPROFILE '.claude'),
    [switch]$ShowCosts,
    [switch]$NoTest,
    [switch]$Uninstall
)

$ErrorActionPreference = 'Stop'
$Utf8NoBom = New-Object Text.UTF8Encoding($false)

$StatuslineScript = @'
__STATUSLINE_SCRIPT__
'@

$ScriptName = 'statusline.mjs'
$CacheName = 'statusline-cost-cache.json'

function Write-Step([string]$level, [string]$message) {
    $color = @{ OK = 'Green'; INFO = 'Gray'; WARN = 'Yellow'; ERROR = 'Red' }[$level]
    Write-Host ('[{0}]{1}{2}' -f $level, (' ' * [Math]::Max(1, 7 - $level.Length)), $message) -ForegroundColor $color
}

# Re-indents compressed JSON with two spaces (PowerShell 5.1 formats JSON badly).
function Format-Json([string]$json) {
    $sb = New-Object Text.StringBuilder
    $indent = 0
    $inString = $false
    $escaped = $false
    for ($i = 0; $i -lt $json.Length; $i++) {
        $c = $json[$i]
        if ($inString) {
            [void]$sb.Append($c)
            if ($escaped) { $escaped = $false }
            elseif ($c -eq '\') { $escaped = $true }
            elseif ($c -eq '"') { $inString = $false }
        }
        elseif ($c -eq '"') { $inString = $true; [void]$sb.Append($c) }
        elseif ($c -eq '{' -or $c -eq '[') {
            $close = if ($c -eq '{') { '}' } else { ']' }
            if ($i + 1 -lt $json.Length -and $json[$i + 1] -eq $close) {
                [void]$sb.Append($c).Append($close)
                $i++
            } else {
                $indent++
                [void]$sb.Append($c).Append("`n").Append('  ' * $indent)
            }
        }
        elseif ($c -eq '}' -or $c -eq ']') {
            $indent--
            [void]$sb.Append("`n").Append('  ' * $indent).Append($c)
        }
        elseif ($c -eq ',') { [void]$sb.Append(",`n").Append('  ' * $indent) }
        elseif ($c -eq ':') { [void]$sb.Append(': ') }
        else { [void]$sb.Append($c) }
    }
    return $sb.ToString() + "`n"
}

function Read-Settings([string]$path) {
    if (-not (Test-Path $path)) { return [pscustomobject]@{} }
    $raw = [IO.File]::ReadAllText($path, [Text.Encoding]::UTF8)
    $parsed = $raw | ConvertFrom-Json          # throws on invalid JSON - caller reports it
    if (-not $parsed) { return [pscustomobject]@{} }
    return $parsed
}

function Save-Settings($settings, [string]$path) {
    if (Test-Path $path) {
        $backup = "$path.bak-$(Get-Date -Format 'yyyyMMdd-HHmmss')"
        Copy-Item $path $backup
        Write-Step OK "Backup: $backup"
    }
    $json = $settings | ConvertTo-Json -Depth 100 -Compress
    # PowerShell 5.1 escapes these characters needlessly
    $json = $json -replace '\\u003c', '<' -replace '\\u003e', '>' -replace '\\u0026', '&' -replace '\\u0027', "'"
    [IO.File]::WriteAllText($path, (Format-Json $json), $Utf8NoBom)
    Write-Step OK "Saved: $path"
}

# Returns the full path of a working Node >= 18, or $null.
# The status line runs on every redraw, so a missing Node means no status line at all.
function Find-Node {
    $ErrorActionPreference = 'Continue'
    foreach ($cmd in @(Get-Command 'node' -All -ErrorAction SilentlyContinue)) {
        try {
            $out = & $cmd.Source --version 2>$null
            if ($out -match '^v(\d+)\.') {
                if ([int]$Matches[1] -ge 18) { return $cmd.Source }
                Write-Step WARN "Skipping $($cmd.Source): Node $out is older than v18."
            }
        } catch { }
    }
    return $null
}

function Get-StatuslineCommand([string]$nodePath, [string]$scriptPath) {
    # Quote both: either can sit under a path with spaces.
    return '"{0}" "{1}"' -f $nodePath, $scriptPath
}

# True if the configured statusLine belongs to this installation.
function Test-OurStatusline($settings, [string]$scriptPath) {
    if (-not $settings.statusLine) { return $false }
    $cmd = [string]$settings.statusLine.command
    if (-not $cmd) { return $false }
    return $cmd.ToLowerInvariant().Contains($scriptPath.ToLowerInvariant())
}

# ------------------------------------------------------------------ Uninstall

if ($Uninstall) {
    Write-Host ''
    Write-Host 'claude-code-statusline - uninstall'
    Write-Host ''

    $scriptPath = Join-Path $ClaudeDir $ScriptName
    $settingsPath = Join-Path $ClaudeDir 'settings.json'

    if (Test-Path $settingsPath) {
        try {
            $settings = Read-Settings $settingsPath
            if (Test-OurStatusline $settings $scriptPath) {
                $settings.PSObject.Properties.Remove('statusLine')
                Save-Settings $settings $settingsPath
                Write-Step OK 'Status line removed from settings.json'
            } else {
                Write-Step INFO 'settings.json points at a different status line - left untouched'
            }
        } catch {
            Write-Step ERROR "Could not read settings.json: $($_.Exception.Message)"
        }
    }

    foreach ($f in $scriptPath, (Join-Path $ClaudeDir $CacheName)) {
        if (Test-Path $f) {
            Remove-Item $f -Force
            Write-Step OK "Removed: $f"
        }
    }

    Write-Host ''
    Write-Host 'Done. Restart Claude Code for the change to take effect.'
    return
}

# -------------------------------------------------------------------- Install

Write-Host ''
Write-Host 'claude-code-statusline - a status line for Claude Code'
Write-Host "Target: $ClaudeDir"
Write-Host ''

$node = Find-Node
if (-not $node) {
    Write-Step ERROR 'Node.js 18 or newer is required but was not found.'
    Write-Host ''
    Write-Host 'Install it from https://nodejs.org (or winget install OpenJS.NodeJS.LTS),'
    Write-Host 'open a new terminal so PATH is refreshed, then run this installer again.'
    exit 1
}
Write-Step OK "Node: $node"

New-Item -ItemType Directory -Force $ClaudeDir -ErrorAction SilentlyContinue | Out-Null

# 1. The script itself
$scriptPath = Join-Path $ClaudeDir $ScriptName
$script = $StatuslineScript
if ($ShowCosts) {
    $script = $script -replace '(?m)^const SHOW_COSTS = false;', 'const SHOW_COSTS = true;'
}
[IO.File]::WriteAllText($scriptPath, $script, $Utf8NoBom)
Write-Step OK "Status line script: $scriptPath"

if ($ShowCosts) {
    Write-Step OK 'Cost line: on (reads local transcripts, sends nothing)'
} else {
    Write-Step INFO 'Cost line: off - re-run with -ShowCosts to enable it'
}

# 2. settings.json
$settingsPath = Join-Path $ClaudeDir 'settings.json'
try {
    $settings = Read-Settings $settingsPath
} catch {
    Write-Step ERROR "settings.json is not valid JSON: $($_.Exception.Message)"
    Write-Host 'Fix or remove the file, then run this installer again.'
    exit 1
}

$command = Get-StatuslineCommand $node $scriptPath

if ($settings.statusLine -and -not (Test-OurStatusline $settings $scriptPath)) {
    Write-Step WARN 'A different status line is configured. It will be replaced.'
    Write-Step INFO "  was: $([string]$settings.statusLine.command)"
}

$entry = [pscustomobject]@{ type = 'command'; command = $command; padding = 0 }
$settings | Add-Member -MemberType NoteProperty -Name statusLine -Value $entry -Force
Save-Settings $settings $settingsPath
Write-Step OK 'Status line registered in settings.json'

# 3. Show what it will look like
if (-not $NoTest) {
    Write-Host ''
    Write-Host 'Sample render:'
    $tmp = Join-Path ([IO.Path]::GetTempPath()) ("statusline-sample-{0}.json" -f [guid]::NewGuid().ToString('N'))
    try {
        $sample = @{
            model = @{ display_name = 'Opus 5 (1M context)' }
            workspace = @{ current_dir = (Get-Location).Path }
            context_window = @{ used_percentage = 8; total_input_tokens = 87200; context_window_size = 1000000 }
            cost = @{ total_duration_ms = 3542000 }
            rate_limits = @{
                # ToUnixTimeSeconds instead of parsing "Get-Date -UFormat %s": that string
                # is culture-dependent and misreads under a comma-decimal locale.
                five_hour = @{ used_percentage = 11; resets_at = [DateTimeOffset]::UtcNow.ToUnixTimeSeconds() + 3300 }
                seven_day = @{ used_percentage = 5 }
            }
        } | ConvertTo-Json -Depth 10 -Compress
        [IO.File]::WriteAllText($tmp, $sample, $Utf8NoBom)
        # Claude Code hands the status line its JSON on stdin. A PowerShell pipeline does
        # not give the child a stdin the script can read, so cmd does the redirection.
        & cmd /c "`"$node`" `"$scriptPath`" < `"$tmp`""
        Write-Host ''
    } catch {
        Write-Step WARN "Could not render a sample: $($_.Exception.Message)"
    } finally {
        Remove-Item $tmp -Force -ErrorAction SilentlyContinue
    }
}

Write-Host ''
Write-Host 'Done. Open /statusline in Claude Code once, or restart it.'
if (-not $ShowCosts) {
    Write-Host 'Want a cost estimate too? Run the installer again with -ShowCosts.'
}
